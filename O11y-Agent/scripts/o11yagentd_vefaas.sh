#!/usr/bin/env sh

# Usage Scenario: Launch oneagentd in VeFaaS environment from local bundle, and launch oneagent based on built-in CR
# Convention Directory Structure Example:
#   <bundle>/
#     o11yagentd/
#       o11yagentd
#       o11yagentctl
#       data/cr/default.yaml
#     scripts/
#       o11yagentd_vefaas.sh
#
# Examples:
#   1) Default install to <bundle>/o11yagentd:
#      APP_REGION=cn-beijing \
#      sh <bundle>/scripts/o11yagentd_vefaas.sh start
#
#   2) Explicitly specify download.registry (override default generation rule):
#      APP_REGION=cn-beijing \
#      sh <bundle>/scripts/o11yagentd_vefaas.sh start \
#        --download.registry https://o11yagent-registry-cn-beijing.ivolces.com
#
#   3) Override install_dir for testing (must ensure data/cr etc. exist):
#      APP_REGION=cn-beijing \
#      sh <bundle>/scripts/o11yagentd_vefaas.sh start \
#        --install_dir /tmp/o11yagent_test
#
# Features:
#   1) Automatically locate bundle root, default install dir is <bundle>/o11yagentd
#   2) Generate config based on bundle's o11yagentd to <install_dir>/conf/o11yagentd.yaml:
#        - deploy_env=vefaas
#        - credentials.region = APP_REGION env
#        - site default volcengine (override via --site)
#        - remote_manager.address use 127.0.0.1 placeholder
#        - download.registry: if not specified via --download.registry, generated by default_registry_address_url
#        - api_server.address = unix://<install_dir>/sock/o11yagentd.sock
#   3) Start <bundle>/o11yagentd/o11yagentd start --conf-dir <install_dir>/conf in foreground via exec
#      (The script process becomes oneagentd process, no sock probe performed)
#   5) Network independent; launch oneagent based on <install_dir>/data/cr/default.yaml
#        - Optional param --cr.registry=file:///abs/path overrides spec.registry in CR

set -e

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
BUNDLE_DIR=$(cd "${SCRIPT_DIR}/.." && pwd)
BUNDLE_O11YAGENTD_DIR="${BUNDLE_DIR}/o11yagentd"

DEFAULT_SITE="volcengine"
DEFAULT_INSTALL_DIR="${BUNDLE_O11YAGENTD_DIR}"
DEFAULT_O11YAGENTD_DISK_IO_THROUGHPUT_LIMIT="51200000"

print_usage() {
    cat <<EOF
Usage:
  sh $0 start [options]

Options:
  --site SITE                 站点, 默认: ${DEFAULT_SITE}
  --control_plane_region R    控制平面 Region, 默认等于 APP_REGION (部分 Region 会内部映射)
  --registry_env ENV          registry 环境, 如 boe, 会作为 -boe 拼接到域名中
  --inner                     使用内部域名后缀, 对应域名中的 -inner 片段
  --download.registry URL     显式覆盖下载 registry 地址
  --install_dir DIR           oneagentd 工作目录, 默认: ${DEFAULT_INSTALL_DIR}
  --cr.registry FILE_URL      覆盖 CR 中 spec.registry (file:// 绝对路径)

Environment:
  APP_REGION                  必填, 作为 region 传入并生成 download.registry, 同时写入 credentials.region
EOF
}

# Reuse download.registry generation rules from oneagentd.sh
default_registry_address_url() {
    site="$1"
    region="$2"
    control_plane_region="$3"
    registry_env="$4"
    inner="$5"

    registry_region="${control_plane_region}"
    url=""

    case "${site}" in
        "volcengine")
            case "${registry_region}" in
                "cn-north-1-dedicated")
                    url="https://o11yagent-registry${registry_env}-${registry_region}.dualstack.cn-beijing.tos.volces.com"
                ;;
                "cn-guilin-boe")
                    registry_region="cn-boe"
                    if [ "${region}" = "cn-chengdu-sdv" ]; then
                        url="https://o11yagent-registry${registry_env}-${registry_region}.tos-${registry_region}${inner}.volces.com"
                    fi
                ;;
            esac
            if [ "${url}" = "" ]; then
                url="https://o11yagent-registry${registry_env}-${registry_region}.tos-${registry_region}${inner}.ivolces.com"
            fi
        ;;
        "byteplus")
            case "${registry_region}" in
                "cn-beijing" | "cn-shanghai" | "cn-guangzhou")
                    url="https://o11yagent-registry${registry_env}-${registry_region}-${site}.tos-${registry_region}${inner}.ibytepluses.com.cn"
                ;;
                "cn-hongkong" | "ap-southeast-1" | "ap-southeast-3")
                    url="https://o11yagent-registry${registry_env}-${registry_region}.tos-${registry_region}${inner}.ibytepluses.com"
                ;;
            esac
            if [ "${url}" = "" ]; then
                url="https://o11yagent-registry${registry_env}-${registry_region}-${site}.tos-${registry_region}${inner}.ibytepluses.com"
            fi
        ;;
        * )
            echo "unsupported site: ${site}" >&2
            exit 1
        ;;
    esac

    echo "${url}"
}

default_remote_manager_url() {
    site="$1"
    control_plane_region="$2"
    registry_env="$3"
    url=""

    case "${site}" in
        "volcengine")
            case "${control_plane_region}" in
                "cn-north-1-dedicated")
                    url="https://o11yagent-platform${registry_env}.cloudmonitor.${control_plane_region}.inner.ivolces.com"
                ;;
                *)
                    url="https://o11yagent-platform${registry_env}.cloudmonitor.${control_plane_region}.ivolces.com"
                ;;
            esac
        ;;
        "byteplus")
            case "${control_plane_region}" in
                "cn-beijing" | "cn-shanghai" | "cn-guangzhou")
                    url="https://o11yagent-platform${registry_env}.cloudmonitor.${control_plane_region}.ivolces.com"
                ;;
                *)
                    url="https://o11yagent-platform${registry_env}.cloudmonitor.${control_plane_region}.ibytepluses.com"
                ;;
            esac
        ;;
        * )
            echo "unsupported site: ${site}"
            exit 1
        ;;
    esac

    echo "${url}"
}

